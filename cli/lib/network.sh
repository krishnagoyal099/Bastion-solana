get_recent_signatures() {
    local pubkey="$1"
    local limit="${2:-10}"

    rpc_call "getSignaturesForAddress" "[\"$pubkey\",{\"limit\":$limit}]" 10
}

check_transaction() {
    local signature="$1"

    rpc_call "getTransaction" "[\"$signature\",{\"encoding\":\"json\",\"maxSupportedTransactionVersion\":0}]" 10
}

# ═══════════════════════════════════════════════════════════════════
# Pool/AMM Functions — Real On-Chain Data
# ═══════════════════════════════════════════════════════════════════
get_pool_reserves() {
    # Try real on-chain data first via solana_tx module
    if declare -f get_pool_reserves_live &>/dev/null; then
        local live_data
        live_data=$(get_pool_reserves_live 2>/dev/null) || true
        if [[ -n "$live_data" ]] && [[ "$live_data" != "ERROR:"* ]]; then
            echo "$live_data"
            return 0
        fi
    fi

    # Fallback: Try direct vault balance query
    local result
    result=$(rpc_call "getProgramAccounts" \
        "[\"$BASTION_AMM_PROGRAM\",{\"encoding\":\"base64\",\"filters\":[{\"dataSize\":246}]}]" 5 2>/dev/null) || true

    if [[ -n "$result" ]] && echo "$result" | grep -q '"result":\[{' 2>/dev/null; then
        # Parse pool account and get vault balances
        python3 << PYEOF 2>/dev/null
import json, base64, struct, sys

data = json.loads('''$result''')
accounts = data.get('result', [])

if not accounts:
    print("ERROR:NO_POOLS")
    sys.exit(0)

raw = base64.b64decode(accounts[0]['account']['data'][0])
if len(raw) < 200:
    print("ERROR:INVALID_DATA")
    sys.exit(0)

# vault_a at offset 8+96, vault_b at offset 8+128
vault_a = raw[104:136]
vault_b = raw[136:168]

def encode_b58(b):
    alphabet = '123456789ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz'
    n = int.from_bytes(b, 'big')
    r = ''
    while n > 0:
        n, m = divmod(n, 58)
        r = alphabet[m] + r
    return ('1' * sum(1 for x in b if x == 0)) + (r or '1')

print(json.dumps({"vault_a": encode_b58(vault_a), "vault_b": encode_b58(vault_b)}))
PYEOF
        return 0
    fi

    echo "ERROR:CONTRACT_UNAVAILABLE"
    return 1
}

calculate_swap_output() {
    local amount_in="$1"
    local reserve_in="$2"
    local reserve_out="$3"

    # x * y = k formula with 0.3% fee
    python3 -c "
amount_in = float('$amount_in')
reserve_in = float('$reserve_in')
reserve_out = float('$reserve_out')

amount_in_with_fee = amount_in * 0.997
numerator = amount_in_with_fee * reserve_out
denominator = reserve_in + amount_in_with_fee
amount_out = numerator / denominator

print(f'{amount_out:.4f}')
" 2>/dev/null || echo "0"
}

# ═══════════════════════════════════════════════════════════════════
# Airdrop Helper (devnet/localnet only)
# ═══════════════════════════════════════════════════════════════════
request_airdrop() {
    local pubkey="$1"
    local sol_amount="${2:-1}"

    if command -v solana &>/dev/null; then
        solana airdrop "$sol_amount" "$pubkey" --url "$SOLANA_RPC_URL" 2>/dev/null
    else
        local lamports
        lamports=$(python3 -c "print(int($sol_amount * 1e9))" 2>/dev/null) || return 1
        rpc_call "requestAirdrop" "[\"$pubkey\",$lamports]" 10
    fi
}
